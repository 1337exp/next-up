import { describe, expect, it } from 'vitest';
import { parseQuick } from '@/core/quick';

// 29 октября 2026 — четверг
const TODAY = '2026-10-29';
const parse = (text: string) => parseQuick(text, TODAY);

describe('быстрый ввод: срок', () => {
    it('без указания срока — сегодня, текст не меняется', () => {
        expect(parse('позвонить маме')).toMatchObject({ body: 'позвонить маме', due: TODAY, repeat: null, foundDue: false, foundRepeat: false });
    });

    it.each([
        ['позвонить маме завтра', 'позвонить маме', '2026-10-30'],
        ['Завтра позвонить маме', 'позвонить маме', '2026-10-30'],
        ['сдать отчёт на завтра', 'сдать отчёт', '2026-10-30'],
        ['послезавтра врач', 'врач', '2026-10-31'],
        ['купить хлеб сегодня', 'купить хлеб', TODAY],
        ['в пятницу оплатить интернет', 'оплатить интернет', '2026-10-30'],
        ['встреча в четверг', 'встреча', '2026-11-05'], // сегодня четверг: имеется в виду следующий
        ['в воскресенье уборка', 'уборка', '2026-11-01'],
        ['через 3 дня позвонить', 'позвонить', '2026-11-01'],
        ['через 2 недели отчёт', 'отчёт', '2026-11-12'],
        ['через неделю', 'через неделю', '2026-11-05'], // всё вырезано: остаётся исходный текст
        ['через месяц продлить', 'продлить', '2026-11-29'],
        ['5 ноября день рождения', 'день рождения', '2026-11-05'],
        ['до 3 янв сдать', 'сдать', '2027-01-03'],
        ['оплатить 30.10', 'оплатить', '2026-10-30'],
        ['оплатить 5.3', 'оплатить', '2027-03-05'], // 5 марта этого года уже прошло
        ['на 5.3.27 встреча', 'встреча', '2027-03-05'],
        ['call mom tomorrow', 'call mom', '2026-10-30'],
        ['dentist on friday', 'dentist', '2026-10-30'],
        ['in 3 days pay rent', 'pay rent', '2026-11-01'],
        ['oct 31 party', 'party', '2026-10-31'],
    ])('%s', (text, body, due) => {
        const result = parse(text);
        expect(result.body).toBe(body);
        expect(result.due).toBe(due);
        expect(result.foundDue).toBe(true);
    });

    it('невозможная дата не вырезается и не переносится на следующий месяц', () => {
        expect(parse('отчёт 31.02')).toMatchObject({ body: 'отчёт 31.02', due: TODAY, foundDue: false });
    });

    it('слова, похожие на дату, но ею не являющиеся, остаются в тексте', () => {
        expect(parse('окружающая среда').foundDue).toBe(false);
        expect(parse('купить 3 дня').foundDue).toBe(false);
        expect(parse('счёт №5 за март').foundDue).toBe(false);
    });
});

describe('быстрый ввод: повтор', () => {
    it.each([
        ['принять витамины каждый день', 'принять витамины', { every: 1, unit: 'day' }, TODAY],
        ['полив цветов каждую неделю', 'полив цветов', { every: 1, unit: 'week' }, TODAY],
        ['платёж каждый месяц', 'платёж', { every: 1, unit: 'month' }, TODAY],
        ['ежегодно техосмотр', 'техосмотр', { every: 1, unit: 'year' }, TODAY],
        ['каждые 2 недели уборка', 'уборка', { every: 2, unit: 'week' }, TODAY],
        ['каждые 3 дня полив', 'полив', { every: 3, unit: 'day' }, TODAY],
        ['every day stretch', 'stretch', { every: 1, unit: 'day' }, TODAY],
    ])('%s', (text, body, repeat, due) => {
        expect(parse(text)).toMatchObject({ body, repeat, due, foundRepeat: true });
    });

    it('«каждый понедельник» — раз в неделю, начиная с ближайшего понедельника', () => {
        expect(parse('планёрка каждый понедельник #работа')).toMatchObject({ body: 'планёрка #работа', repeat: { every: 1, unit: 'week' }, due: '2026-11-02' });
    });

    it('повтор и срок вместе: «завтра, каждый день»', () => {
        expect(parse('зарядка каждый день, начиная с завтра')).toMatchObject({ repeat: { every: 1, unit: 'day' }, due: '2026-10-30' });
    });

    it('слишком большой период не принимается', () => {
        expect(parse('каждые 150 дней что-то').foundRepeat).toBe(false);
    });
});

describe('быстрый ввод: теги и пустое', () => {
    it('хештеги остаются в тексте', () => {
        expect(parse('отчёт #работа завтра').body).toBe('отчёт #работа');
    });

    it('пустой ввод не падает', () => {
        expect(parse('   ')).toMatchObject({ body: '', due: TODAY, repeat: null });
    });
});
