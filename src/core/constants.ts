/** Заметки со сроком старше стольких дней удаляются. */
export const RETENTION_DAYS = 365;
/** Содержимое заметок дальше этого срока можно сворачивать (настройка). */
export const FAR_DAYS = 21;
/** Заметки ближе этого срока подсвечиваются как «скоро». */
export const SOON_DAYS = 7;
/** Сколько дней удалённая заметка видна в корзине. */
export const TRASH_DAYS = 30;
/** Сколько дней хранится сам факт удаления: за это время его должна подхватить синхронизация. */
export const TOMBSTONE_DAYS = 90;
/** От скольких подряд идущих архивных повторов одной серии они сворачиваются в одну строку. */
export const RUN_MIN = 3;

export const MS_PER_DAY = 86_400_000;
/** Насколько «состаривается» удаление при «удалить навсегда»: заметка пропадает из корзины, оставшись надгробием. */
export const PURGED_AGE_MS = TRASH_DAYS * MS_PER_DAY + 1;
